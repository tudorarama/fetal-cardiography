VENV_PYTHON = ROOT / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def ensure_venv():
    """Re-runs the current script with four_chambers/.venv if started with another Python.

    The folder has its own environment (CUDA PyTorch + nnU-Net); the project's
    root .venv is CPU-only and has no nnU-Net, so "python train.py" from the
    wrong environment would fail with "No module named 'nnunetv2'".
    """
    import subprocess
    import sys
    if Path(sys.prefix).resolve() == (ROOT / ".venv").resolve() or not VENV_PYTHON.exists():
        return
    print(f"(using {VENV_PYTHON})", flush=True)
    sys.exit(subprocess.run([str(VENV_PYTHON), sys.argv[0], *sys.argv[1:]]).returncode)


def setup_nnunet_env():
    """Environment variables nnU-Net v2 reads (set before importing nnunetv2)."""
    os.environ["nnUNet_raw"] = str(NNUNET_DIR / "raw")
    os.environ["nnUNet_preprocessed"] = str(NNUNET_DIR / "preprocessed")
    os.environ["nnUNet_results"] = str(NNUNET_DIR / "results")
    os.environ.setdefault("nnUNet_compile", "f")    # torch.compile needs triton, not on Windows
    os.environ.setdefault("nnUNet_n_proc_DA", "6")  # data augmentation workers (12 CPU threads)
    for k in ("raw", "preprocessed", "results"):
        (NNUNET_DIR / k).mkdir(parents=True, exist_ok=True)
